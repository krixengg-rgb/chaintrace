    assert keccak256(b"").hex() == "c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470"
    assert to_checksum("0x28c6c06298d514db089934071355e5743bf21d60") == "0x28C6c06298d514Db089934071355E5743bf21d60"
    print("ok")
